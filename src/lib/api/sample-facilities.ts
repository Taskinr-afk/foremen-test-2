import type { Classification, Determination, Establishment, Incident, Outcome, Review } from '../schemas/incident';
import { ENGINE, HOUR, fact, type SampleAnalysis } from './mock';

// Sample facilities beyond the construction site in mock.ts, so the demo covers other industries
// that keep an OSHA 300 log. Every outcome and citation follows 29 CFR 1904.

type Draft = Omit<Incident, 'caseNumber' | 'caseType' | 'daysAway' | 'daysRestricted' | 'privacyCase' | 'severeAlert'> &
  Partial<Pick<Incident, 'caseNumber' | 'caseType' | 'daysAway' | 'daysRestricted' | 'privacyCase' | 'severeAlert'>>;

function inc(d: Draft): Incident {
  return { caseNumber: null, caseType: 'injury', daysAway: 0, daysRestricted: 0, privacyCase: false, severeAlert: null, ...d };
}

function det(outcome: Outcome, classification: Classification | null, reason: string, citations: string[], openQuestions: string[] = []): Determination {
  return { outcome, classification, reason, citations, openQuestions, engineVersion: ENGINE };
}

const PENDING: Review = { status: 'pending' };

function accepted(at: string, outcome: 'recordable' | 'not-recordable', classification: Classification | null): Review {
  return { status: 'accepted', reviewer: 'Test Manager', at, outcome, classification };
}

